// ---------------------------------------------------------------- sections

interface SectionDef {
  file: string;
  markup: string;
  schema: Record<string, unknown>;
}

function schemaFor(section: Section, extraSettings: Record<string, unknown>[]): Record<string, unknown> {
  return {
    name: section.title || section.type,
    settings: [
      { type: "text", id: "heading", label: "Heading", default: section.title },
      { type: "text", id: "subheading", label: "Subheading", default: section.subtitle },
      { type: "textarea", id: "text", label: "Text", default: section.text },
      { type: "image_picker", id: "image", label: "Image" },
      { type: "color", id: "bg_color", label: "Background color", default: section.bgColor },
      { type: "color", id: "text_color", label: "Text color", default: section.textColor },
      ...extraSettings,
    ],
    presets: [{ name: section.title || section.type }],
  };
}

function sectionLiquid(def: SectionDef, note: string): string {
  return `{% comment %}\n  ${note}\n  ${PLACEHOLDER_DISCLAIMER}\n{% endcomment %}\n${def.markup}\n{% schema %}\n${JSON.stringify(def.schema, null, 2)}\n{% endschema %}\n`;
}

function buildSectionDef(section: Section, project: Project): SectionDef {
  const file = sectionFileName(section.type);
  const img = section.image || "https://picsum.photos/seed/placeholder/1200/800";
  switch (section.type) {
    case "header":
      return {
        file,
        markup: `<header class="site-header" style="background: {{ section.settings.bg_color }}; color: {{ section.settings.text_color }};">\n  <div class="container">\n    <a class="site-logo" href="/">{{ shop.name | default: '${esc(project.name)}' }}</a>\n    <button data-nav-toggle aria-label="Menu">☰</button>\n    <nav class="site-nav">\n      {%- for link in linklists.main-menu.links -%}\n        <a href="{{ link.url }}">{{ link.title }}</a>\n      {%- else -%}\n        <a href="/">Home</a><a href="/collections/all">Shop</a>\n      {%- endfor -%}\n    </nav>\n    <a href="/cart">Cart (0)</a>\n  </div>\n</header>`,
        schema: schemaFor(section, []),
      };
    case "hero":
      return {
        file,
        markup: `<section class="hero" style="background: {{ section.settings.bg_color }}; color: {{ section.settings.text_color }}; padding: {{ section.settings.padding | default: '48px' }};">\n  <div class="container">\n    {%- if section.settings.image -%}<img src="{{ section.settings.image | image_url: width: 1200 }}" alt="{{ section.settings.heading | escape }}">{%- else -%}<img src="${img}" alt="{{ section.settings.heading | escape }}">{%- endif -%}\n    <h1>{{ section.settings.heading | escape }}</h1>\n    <p>{{ section.settings.subheading | escape }}</p>\n    <p>{{ section.settings.text | escape }}</p>\n    <a class="btn" href="/collections/all">Shop now</a>\n  </div>\n</section>`,
        schema: schemaFor(section, [
          { type: "text", id: "padding", label: "Padding", default: `${section.padding ?? 48}px 0` },
        ]),
      };
    case "banner":
      return {
        file,
        markup: `<section class="banner" style="background: {{ section.settings.bg_color }}; color: {{ section.settings.text_color }}; padding: 32px 20px;">\n  <div class="container">\n    <h2>{{ section.settings.heading | escape }}</h2>\n    <p>{{ section.settings.text | escape }}</p>\n  </div>\n</section>`,
        schema: schemaFor(section, []),
      };
    case "category":
      return {
        file,
        markup: `<section style="background: {{ section.settings.bg_color }}; color: {{ section.settings.text_color }}; padding: 40px 0;">\n  <div class="container">\n    <h2 style="text-align: {{ section.settings.align | default: 'center' }};">{{ section.settings.heading | escape }}</h2>\n    <p style="text-align: {{ section.settings.align | default: 'center' }};">{{ section.settings.text | escape }}</p>\n    <div class="grid">\n      {%- for collection in collections limit: 3 -%}\n        <a class="card" href="{{ collection.url }}"><div class="card-body"><h3>{{ collection.title }}</h3></div></a>\n      {%- else -%}\n        <div class="card"><img src="${img}" alt="Placeholder category"><div class="card-body"><h3>Placeholder category</h3><p class="placeholder-note">Add a real collection in Shopify.</p></div></div>\n      {%- endfor -%}\n    </div>\n  </div>\n</section>`,
        schema: schemaFor(section, [
          { type: "select", id: "align", label: "Alignment", options: [
            { value: "left", label: "Left" }, { value: "center", label: "Center" }, { value: "right", label: "Right" },
          ], default: section.align || "center" },
        ]),
      };
    case "product":
      return {
        file,
        markup: `<section style="background: {{ section.settings.bg_color }}; color: {{ section.settings.text_color }}; padding: 40px 0;">\n  <div class="container">\n    <h2>{{ section.settings.heading | escape }}</h2>\n    <p>{{ section.settings.text | escape }}</p>\n    <div class="grid">\n      {%- for product in collections.all.products limit: 4 -%}\n        {% render 'product-card', product: product %}\n      {%- else -%}\n        {% render 'product-card' %}\n        {% render 'product-card' %}\n        {% render 'product-card' %}\n        {% render 'product-card' %}\n      {%- endfor -%}\n    </div>\n    <p class="placeholder-note">${PLACEHOLDER_DISCLAIMER}</p>\n  </div>\n</section>`,
        schema: schemaFor(section, []),
      };
    case "features":
      return {
        file,
        markup: `<section style="background: {{ section.settings.bg_color }}; color: {{ section.settings.text_color }}; padding: 40px 0;">\n  <div class="container">\n    <h2 style="text-align: center;">{{ section.settings.heading | escape }}</h2>\n    <div class="features">\n      <div><h3>Free shipping</h3><p>{{ section.settings.text | escape }}</p></div>\n      <div><h3>Easy returns</h3><p>30-day returns on every order.</p></div>\n      <div><h3>Secure checkout</h3><p>Safe payments with Shopify checkout.</p></div>\n    </div>\n  </div>\n</section>`,
        schema: schemaFor(section, []),
      };
    case "footer":
      return {
        file,
        markup: `<footer class="site-footer" style="background: {{ section.settings.bg_color }}; color: {{ section.settings.text_color }};">\n  <div class="container">\n    <div><strong>{{ shop.name | default: '${esc(project.name)}' }}</strong><p>{{ section.settings.text | escape }}</p></div>\n    <div><a href="/">Home</a><br><a href="/collections/all">Shop</a><br><a href="/pages/contact">Contact</a></div>\n    <div><p>&copy; {{ 'now' | date: '%Y' }} {{ shop.name | default: '${esc(project.name)}' }}</p></div>\n  </div>\n</footer>`,
        schema: schemaFor(section, []),
      };
    case "cta":
      return {
        file,
        markup: `<section class="cta" style="background: {{ section.settings.bg_color }}; color: {{ section.settings.text_color }}; padding: 48px 20px;">\n  <div class="container">\n    <h2>{{ section.settings.heading | escape }}</h2>\n    <p>{{ section.settings.text | escape }}</p>\n    <a class="btn" href="/collections/all">{{ section.settings.subheading | escape | default: 'Shop now' }}</a>\n  </div>\n</section>`,
        schema: schemaFor(section, []),
      };
  }
}

