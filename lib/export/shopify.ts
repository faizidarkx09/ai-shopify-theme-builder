// valid theme structure me badla jata hai:
//   layout/theme.liquid, templates/*.liquid, sections/*.liquid,
//   snippets/*.liquid, assets/theme.css + theme.js,
//   config/settings_schema.json + settings_data.json,
//   locales/en.default.json
