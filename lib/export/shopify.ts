// Har section Shopify ke "sections with schema" tareeqe se banta hai:
// markup me {{ section.settings.* }} use hota hai aur asal content
// {% schema %} ke defaults me hota hai, taake user Shopify Theme
// Editor se bhi text/colors badal sake.
