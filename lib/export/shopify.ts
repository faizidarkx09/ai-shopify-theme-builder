function slugify(value: string): string {
  return value
    .toLowerCase()
    .trim()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "") || "theme";
}

function esc(value: string): string {
  return value
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;");
}

/** Font naam ko CSS font-family stack me badlo. */
function fontStack(font: string): string {
  const map: Record<string, string> = {
    Inter: "'Inter', system-ui, -apple-system, 'Segoe UI', sans-serif",
    Poppins: "'Poppins', system-ui, sans-serif",
    "Playfair Display": "'Playfair Display', Georgia, serif",
    Montserrat: "'Montserrat', system-ui, sans-serif",
    Roboto: "'Roboto', system-ui, sans-serif",
    Lora: "'Lora', Georgia, serif",
    "DM Sans": "'DM Sans', system-ui, sans-serif",
  };
  return map[font] ?? `'${font}', system-ui, sans-serif`;
}

/** Section type -> Shopify section file ka naam.
 *  Wave 0: new types map onto EXISTING files only — the zip stays the
 *  same size. testimonials/faq/trust-badges -> features,
 *  newsletter/custom -> cta, announcement/countdown/delivery -> banner,
 *  bundle/sticky-atc -> product-grid. */
export function sectionFileName(type: SectionType): string {
  const map: Record<SectionType, string> = {
    header: "header",
    hero: "hero",
    banner: "banner",
    category: "category-grid",
    product: "product-grid",
    features: "features",
    footer: "footer",
    cta: "cta",
    testimonials: "features",
    faq: "features",
    newsletter: "cta",
    announcement: "banner",
    countdown: "banner",
    "trust-badges": "features",
    bundle: "product-grid",
    "sticky-atc": "product-grid",
    delivery: "banner",
    custom: "cta",
  };
  return map[type];
}

function findPage(project: Project, slug: string): Page | undefined {
  return project.pages.find((p) => p.slug === slug);
}

function homePage(project: Project): Page {
  return findPage(project, "home") ?? findPage(project, "index") ?? project.pages[0];
}

